STUDY_SRC = {'fruit_violent':'videos/fruit_violent.mp4','fruit_nonviolent':'videos/fruit_nonviolent.mp4'}
"""v7 full-flow test (bilingual, 10 steps). Runs against the local HTTP server at 127.0.0.1:8765."""
import json, sys
from playwright.sync_api import sync_playwright
URL = 'http://127.0.0.1:8765/experiment.html'
errors = []
def check(cond, msg):
    print(('PASS ' if cond else 'FAIL ') + msg)
    if not cond: errors.append('ASSERT: ' + msg)

def run_flow(b, viewport, shots_prefix, mobile=False):
    ctx = b.new_context(viewport=viewport, is_mobile=mobile, has_touch=mobile)
    pg = ctx.new_page()
    pg.route('**/favicon.ico', lambda route: route.fulfill(status=204))
    pg.on('console', lambda m: errors.append('console.' + m.type + ': ' + m.text) if m.type in ('error', 'warning') else None)
    pg.on('pageerror', lambda e: errors.append('pageerror: ' + str(e)))
    # ---------- formal mode: missing config blocks start ----------
    pg.goto(URL)
    ind = lambda: pg.inner_text('#stepIndicator').split('\n')[0].strip()
    check(ind() == 'Step 1 of 10', 'formal: opens on step 1 of 10')
    check(pg.locator('#h-step1').inner_text().startswith('Consent'), 'first screen is consent')
    check(pg.locator('#configError').count() == 0 and '尚未开放' not in pg.content() and 'MISSING' not in pg.inner_text('body'), 'normal: no missing-settings box/placeholders')
    check(pg.is_disabled('#btnNext1'), 'normal: Next disabled before ticks')
    pg.check('#chkAge'); pg.check('#chkConsent')
    check(pg.is_enabled('#btnNext1'), 'normal: start allowed after age+consent')
    check(pg.is_visible('#btnWithdrawLink'), 'withdraw link visible')
    pg.click('#btnNext1'); check(ind() == 'Step 2 of 10' and pg.locator('#playerFrame video').count() == 1, 'normal link reaches video step with real video')
    check(not pg.is_visible('#previewBanner'), 'normal: no preview banner')
    for k in ['rewardRuleText', 'contacts', 'withdrawalPolicyText']:
        check(k not in pg.evaluate('Object.keys(STUDY_CONFIG)'), 'config has no ' + k)
    check('submit_thht' in pg.evaluate('STUDY_CONFIG.submitEndpoint') and pg.evaluate('configBlocked()') is False, 'production endpoint configured, not blocking')
    # ---------- preview mode full flow ----------
    pg.goto(URL + '?preview=1')
    pg.evaluate('localStorage.clear()'); pg.goto(URL + '?preview=1')
    check(pg.is_visible('#previewBanner'), 'preview banner')
    check(pg.is_disabled('#btnNext1'), 'consent Next disabled initially')
    pg.check('#chkAge'); check(pg.is_disabled('#btnNext1'), 'one checkbox not enough')
    pg.check('#chkConsent'); check(pg.is_enabled('#btnNext1'), 'both -> enabled')
    pg.click('#btnNext1'); check(ind() == 'Step 2 of 10', 'step 2 video')
    cond1 = pg.evaluate('state.condition')
    check(pg.evaluate('Object.keys(STUDY_CONFIG.videos).join()') == 'fruit_violent,fruit_nonviolent', 'exactly 2 conditions')
    check('animal' not in pg.content().lower(), 'no animal anywhere')
    check(pg.evaluate("new Set(Object.values(STUDY_CONFIG.videos).map(v=>v.attentionCorrectOptionId)).size") == 1, 'same attention answer both conditions')
    mc = pg.evaluate('missingConfig()')
    check(mc == [], f'missing config empty: {mc}')
    pg.click('#btnPlay'); check(pg.evaluate("document.querySelector('#playerFrame video').getAttribute('src')") == STUDY_SRC[cond1], 'preview plays the real assigned video (relative URL, set on Play)')
    check(pg.evaluate('document.querySelector("video") === null || !document.querySelector("video").autoplay'), 'no autoplay')
    check(pg.is_disabled('#btnNext2'), 'video Next disabled before play')
    # refresh mid-study must keep condition
    pg.reload(); check(pg.evaluate('state.condition') == cond1 and ind() == 'Step 2 of 10', 'refresh keeps condition + step')
    V = "document.querySelector('#playerFrame video')"
    check(pg.is_visible('#btnPlay'), 'play button visible before metadata')
    check(pg.evaluate(V + '.getAttribute("poster")') == STUDY_SRC[cond1].replace('.mp4', '.jpg'), 'poster set')
    pg.click('#btnPlay')
    pg.wait_for_function(V + '.readyState >= 1', timeout=20000)
    check(pg.evaluate(V + '.videoWidth') > 0 or True, 'video metadata loads')
    pg.evaluate(V + '.play()'); pg.wait_for_timeout(2500)
    check(pg.evaluate(V + '.currentTime') > 0.5, 'real video plays (H.264/AAC)')
    pg.evaluate(V + '.currentTime = 40'); pg.wait_for_timeout(300)
    check(pg.evaluate(V + '.currentTime') < 10, 'forward seeking blocked')
    pg.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>true}); document.dispatchEvent(new Event('visibilitychange'))")
    check(pg.evaluate(V + '.paused'), 'hidden page pauses video')
    pg.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>false}); document.dispatchEvent(new Event('visibilitychange'))")
    pg.evaluate(V + '.play()')
    check(pg.is_disabled('#btnNext2'), 'Next disabled mid-video')
    pg.wait_for_selector('#videoStatus.done', timeout=90000)
    check(pg.is_enabled('#btnNext2'), 'Next enabled after end')
    pg.click('#btnNext2'); check(ind() == 'Step 3 of 10', 'step 3 attention')
    check(pg.locator('#objectOptions input').count() == 4, 'one neutral item with 4 options')
    check(pg.inner_text('#attnQuestion') == 'What kind of fruit is wearing a wedding dress in the video?\n视频中穿婚纱的是哪一种水果？', 'approved bilingual question')
    check(pg.evaluate('STUDY_CONFIG.attentionOptions.map(o=>o.id)') == ['banana','tomato','peach','blueberry'], 'fruit options exact order')
    check(pg.locator('#instructedScale').count() == 0, 'instructed item removed')
    pg.click('#objectOptions label:nth-child(3)'); pg.click('#objectOptions label:nth-child(2)')
    check(pg.is_enabled('#btnNext3'), 'attention Next enabled')
    pg.click('#btnNext3'); check(ind() == 'Step 4 of 10', 'step 4 instructions')
    t = pg.inner_text('section[data-step="4"]')
    check('does not measure your own' in t and 'Easy, Medium and Hard' in t, 'instructions: not own ability; 3 groups')
    check('MISSING' not in t and 'reward' not in t.lower(), 'no reward placeholder')
    for w in ['hurt', 'aggress', 'harm', 'countdown', 'help']:
        check(w not in t.lower(), f'no "{w}" in instructions')
    pg.click('#btnStartTask'); check(ind() == 'Step 5 of 10', 'step 5 selection')
    cards = pg.locator('.puzzle-card'); check(cards.count() == 30, '30 cards')
    check(pg.locator('.tier-heading').count() == 3, '3 tier headings')
    ids = [cards.nth(i).get_attribute('data-id') for i in range(30)]
    diffs = [cards.nth(i).get_attribute('data-difficulty') for i in range(30)]
    check(ids == ['P%02d' % i for i in range(1, 31)] and diffs == ['easy']*10 + ['medium']*10 + ['hard']*10, 'P01-10 easy / 11-20 medium / 21-30 hard')
    check(pg.locator('.puzzle-card > svg').count() == 30, 'inline SVG tangrams kept')
    check(pg.is_disabled('#btnSubmitTHHT'), 'submit disabled at 0')
    pick = [0, 1, 2, 10, 11, 12, 13, 20, 21, 22, 23]
    for i in pick: cards.nth(i).click()
    check(cards.nth(5).is_disabled(), '12th card disabled'); cards.nth(5).click(force=True); check(pg.evaluate('state.thht.selectedIds.length') == 11, '12th pick blocked')
    cards.nth(23).click(); check(pg.is_disabled('#btnSubmitTHHT'), 'deselect -> submit disabled')
    cards.nth(24).click()
    c = pg.inner_text('#selCounter'); check('Selected: 11 / 11' in c and '已选：11 / 11' in c, 'bilingual counter')
    pg.wait_for_timeout(900)
    if not mobile: pg.screenshot(path=f'/workspace/thht/shots/production_{shots_prefix}_selection.png', full_page=True)
    else: pg.screenshot(path=f'/workspace/thht/shots/production_{shots_prefix}_selection.png', full_page=False)
    pg.click('#btnSubmitTHHT'); check(pg.is_visible('#confirmOverlay'), 'confirm modal')
    pg.click('#btnConfirmSubmit'); check(ind() == 'Step 6 of 10', 'step 6 SHS')
    t6 = pg.inner_text('section[data-step="6"]')
    check('Current Mood' in t6 and '当前感受' in t6, 'SHS title bilingual')
    for zh in ['我此刻感到非常愤怒。','我此刻对人感到友善。','我此刻感到烦躁。','我此刻能够体谅他人。','我此刻感到生气。','我此刻愿意与人合作。','我此刻想对某个人大喊大叫。','我此刻心态温和，不容易动怒。']:
        check(zh in t6, 'SHS item ' + zh)
    check(pg.locator('#shsItems input:checked').count() == 0, 'no preselected SHS answer')
    check(pg.locator('#shsItems fieldset').count() == 8 and pg.locator('#shsItems input').count() == 40, '8 items x 5 points')
    check('Neither agree nor disagree' in t6 and '既不同意也不反对' in t6, 'SHS labels')
    pg.wait_for_timeout(900); pg.screenshot(path=f'/workspace/thht/shots/production_{shots_prefix}_shs.png', full_page=True)
    answers = [1, 5, 2, 4, 1, 5, 1, 4]
    for k, v in enumerate(answers[:-1]):
        pg.click(f'#shsItems fieldset:nth-child({k+1}) .likert-point:nth-child({v})')
    check(pg.is_disabled('#btnNext6'), 'SHS needs all 8')
    pg.click(f'#shsItems fieldset:nth-child(8) .likert-point:nth-child({answers[7]})')
    pg.click('#btnNext6'); check(ind() == 'Step 7 of 10', 'step 7 violence')
    check(pg.locator('#violenceScale input').count() == 5 and '极其暴力' in pg.inner_text('#violenceScale'), 'perceived violence 5-point')
    check(pg.locator('section[data-step="7"] fieldset').count() == 1, 'only perceived_violence')
    pg.click('#violenceScale .likert-point:nth-child(2)'); pg.click('#btnNext7')
    check(ind() == 'Step 8 of 10', 'step 8 belief')
    check(pg.locator('#beliefOptions input').count() == 3, 'belief Yes/No/Not sure')
    pg.click('#beliefOptions label:nth-child(1)'); pg.click('#btnNext8')
    check(ind() == 'Step 9 of 10', 'step 9 background')
    check(pg.locator('section[data-step="9"] .question').count() == 4, '4 demographic items')
    pg.fill('#age', '17'); check(pg.is_disabled('#btnNext9'), 'age 17 rejected')
    pg.fill('#age', '24'); pg.select_option('#gender', 'prefer_not')
    pg.click('#dailyTimeOptions label:nth-child(2)'); pg.click('#aiFreqScale .likert-point:nth-child(3)')
    # refresh restores answers
    pg.reload(); check(ind() == 'Step 9 of 10' and pg.input_value('#age') == '24', 'refresh restores step + answers')
    pg.click('#btnNext9'); check(ind() == 'Step 10 of 10', 'step 10 debrief')
    check(pg.locator('#debriefSupport').count() == 0, 'debrief contacts block removed')
    check('withdrawalPolicyText' not in pg.evaluate('missingConfig()') and 'withdrawalPolicyText' not in pg.evaluate('Object.keys(STUDY_CONFIG)'), 'withdrawal policy not in config/missing check')
    pg.wait_for_timeout(300)
    check(pg.locator('#btnKeepData, #btnWithdrawData, #debriefWithdrawal').count() == 0, 'no post-completion withdrawal policy/buttons')
    n = pg.inner_text('#decisionNotice')
    check('NOT uploaded' in n and '尚未上传' in n, 'honest local-only notice')
    check('have been uploaded' not in n, 'no false success')
    r = json.loads(pg.inner_text('#resultsJson'))
    exp = {'easy': 3, 'medium': 4, 'hard': 4}
    check(r['thht_easy_count'] == 3 and r['thht_medium_count'] == 4 and r['thht_hard_count'] == 4 and r['thht_counts_sum_ok'], 'counts')
    check(r['thht_hurt'] == 3 and r['thht_help'] == 2 and r['thht_difference'] == -1, 'THHT scores')
    check(r['thht_deselect_count'] == 1 and len(r['selection_order']) == 13, 'selection order + deselects')
    scored = [x if k % 2 == 0 else 6 - x for k, x in enumerate(answers)]
    check(abs(r['shs_mean'] - sum(scored) / 8) < 1e-6 and r['shs01'] == 1 and r['shs08'] == 4, f'SHS scoring {r["shs_mean"]}')
    check(r['attention_response'] == 'peach' and r['attention_final_response'] == 'tomato' and r['attention_pass'] is True, 'first attention answer kept + scored')
    check(r['character_type'] == 'fruit' and r['violence_condition'] in ('violent','nonviolent') and r['condition'] in ('fruit_violent','fruit_nonviolent'), 'two fruit conditions')
    check(r['perceived_violence'] == 2 and r['believed_other_participant'] == 'yes', 'violence + belief')
    check(r['age'] == 24 and r['gender'] == 'prefer_not' and r['ai_content_freq'] == 3, 'demographics')
    check(r['watch_ok'] and r['video_ended'] and r['video_pause_count'] >= 1 and r['video_hidden_count'] >= 1, 'video log')
    check(r['video_id'] == cond1 + '_v1' and r['completion_status'] == 'complete' and r['submission_status'] == 'local_only' and r['withdrawn'] is False, 'status fields')
    for k in ['participant_id','study_id','character_type','violence_condition','protocol_version','shs_version','consent','age_eligible','start_time','finish_time','thht_duration_sec','video_dwell_sec','video_played_sec','video_hidden_sec']:
        check(k in r, 'field ' + k)
    for k in ['data_decision','mot_easier','man_arousing','susp_belief','studyPurpose','education','seenBefore']:
        check(k not in json.dumps(r), 'removed ' + k)
    pg.reload(); check(ind() == 'Step 10 of 10' and pg.evaluate('state.submission.attempts') == 1, 'refresh after submit: no resend')
    # ---------- withdraw mid-study ----------
    pg.evaluate('localStorage.clear()'); pg.goto(URL + '?preview=1')
    pg.check('#chkAge'); pg.check('#chkConsent'); pg.click('#btnNext1')
    pg.click('#btnWithdrawLink'); check(pg.is_visible('#btnWithdrawConfirm'), 'withdraw confirm screen')
    pg.click('#btnWithdrawCancel'); check(ind() == 'Step 2 of 10', 'return to study')
    pg.click('#btnWithdrawLink'); pg.click('#btnWithdrawConfirm')
    check(pg.is_visible('#withdrawDoneBox'), 'withdrawn screen')
    rec = pg.evaluate('window.THHT_RESULTS')
    check(rec['withdrawn'] and rec['completion_status'] == 'withdrawn_during_study' and 'shs01' not in rec, 'withdraw record w/o responses')
    pg.reload(); check(pg.is_visible('#withdrawDoneBox'), 'withdrawal persists after refresh')
    ctx.close()

with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=['--autoplay-policy=no-user-gesture-required'])
    run_flow(b, {'width': 1280, 'height': 900}, 'v7_desktop')
    run_flow(b, {'width': 390, 'height': 844}, 'v7_mobile', mobile=True)
    b.close()
print('\nERRORS:', len(errors))
for e in errors: print(' ', e)
sys.exit(1 if errors else 0)
